import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import {saveEvidence} from './evidence.mjs';
import {dirname,join} from 'node:path';
const [name,command,...args]=process.argv.slice(2);
if(!/^M6_[A-Z0-9_]+$/.test(name??'')||!['npm','node','docker','git'].includes(command))throw Error('Expected M6 evidence name and approved local gate command');
const startedAt=new Date().toISOString(),chunks=[];
const secrets=['DATABASE_URL','MIGRATION_DATABASE_URL','JWT_SECRET','REFRESH_TOKEN_SECRET','POSTGRES_PASSWORD','POSTGRES_APP_PASSWORD'].flatMap(k=>process.env[k]?[process.env[k]]:[]);
const sanitize=value=>secrets.reduce((s,v)=>s.replaceAll(v,'[REDACTED]'),value);
const executable=command==='npm'?process.execPath:command;
const childArgs=command==='npm'?[process.env.npm_execpath??join(dirname(process.execPath),'node_modules/npm/bin/npm-cli.js'),...args]:args;
const child=spawn(executable,childArgs,{shell:false,stdio:['ignore','pipe','pipe']});
for(const stream of [child.stdout,child.stderr])stream.on('data',chunk=>{const s=sanitize(chunk.toString());chunks.push(s);process.stdout.write(s);});
const code=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('exit',resolve);});
await mkdir('docs/verification/evidence/iterations',{recursive:true});
const stamp=startedAt.replace(/[:.]/g,'-');
await writeFile(`docs/verification/evidence/iterations/${name}-${stamp}.txt`,chunks.join(''));
await saveEvidence(`docs/verification/evidence/${name}.json`,{command:[command,...args].join(' '),startedAt,finishedAt:new Date().toISOString(),exitCode:code,status:code===0?'PASS':'FAIL',log:`iterations/${name}-${stamp}.txt`});
process.exitCode=code??1;
