import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { saveEvidence } from './evidence.mjs';
const [name, command, ...args] = process.argv.slice(2);
if (!/^M20_[A-Z0-9_]+$/.test(name ?? '') || !['npm', 'node', 'git'].includes(command)) throw new Error('Expected M20 evidence name and local gate command');
const secrets = ['DATABASE_URL', 'MIGRATION_DATABASE_URL', 'JWT_SECRET', 'REFRESH_TOKEN_SECRET', 'POSTGRES_PASSWORD', 'POSTGRES_APP_PASSWORD'].flatMap(key => process.env[key] ? [process.env[key]] : []);
const sanitize = value => secrets.reduce((text, secret) => text.replaceAll(secret, '[REDACTED]'), value);
const startedAt = new Date().toISOString(), chunks = [];
const executable = command === 'npm' ? process.execPath : command;
const childArgs = command === 'npm' ? [process.env.npm_execpath ?? join(dirname(process.execPath), 'node_modules/npm/bin/npm-cli.js'), ...args] : args;
const child = spawn(executable, childArgs, { shell: false, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
for (const stream of [child.stdout, child.stderr]) stream.on('data', chunk => { const text = sanitize(chunk.toString()); chunks.push(text); process.stdout.write(text); });
const code = await new Promise((resolve, reject) => { child.on('error', reject); child.on('exit', resolve); });
const folder = 'docs/v1.3/evidence/gates'; await mkdir(folder + '/iterations', { recursive: true });
await mkdir('artifacts/m20/gates', { recursive: true });
const log = 'artifacts/m20/gates/' + name + '-' + startedAt.replace(/[:.]/g, '-') + '.txt';
await writeFile(log, chunks.join(''));
await saveEvidence(folder + '/' + name + '.json', { command: [command, ...args].join(' '), startedAt, finishedAt: new Date().toISOString(), exitCode: code, result: code === 0 ? 'PASS' : 'FAIL', log });
process.exitCode = code ?? 1;
